// Assignment Operators

#include <iostream>
using namespace std;

int main()
{
    int x;
    x = 5;   
    cout << x << endl;

    x += 10; 
    cout << x << endl;  

    x -= 3;  
    cout << x << endl;

    x *= 2;  
    cout << x << endl;

    x /= 4;  
    cout << x << endl;

    x %= 3;  
    cout << x << endl;

}