// TYPECASTING OPERATOR

// Typecasting Operators are used to Convert Datatypes.

#include <iostream>
using namespace std;

int main()
{
    char ch = 'a';
    cout << ch;
    cout << endl << (int) ch;
    cout << endl;

    int num = 65;
    cout << num << endl;
    cout << (char) num << endl;

    cout << (char) 69;
}