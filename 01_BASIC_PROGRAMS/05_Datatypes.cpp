// This program demonstrates the use of different data types in C++.

#include <iostream>
using namespace std;

int main()
{
    int num1 = 10;
    float num2 = 3.14;
    char ch = 'A';
    bool isTrue = true;

    cout << "Integer: " << num1 << endl;
    cout << "Float: " << num2 << endl;
    cout << "Character: " << ch << endl;
    cout << "Boolean: " << isTrue << endl;
    return 0;
}